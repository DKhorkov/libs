// Package metrics меряет HTTP-запросы: число, длительность, размер ответа и
// запросы в полёте.
//
// Метка маршрута — шаблон (WithRouteLabel; по умолчанию — шаблон
// стандартного ServeMux), а не путь: идентификаторы в пути дали бы по серии
// на каждый. Метод вне стандартного набора пишется как OTHER. Апгрейды
// соединения (WebSocket) не меряются: их длительность — жизнь сокета.
// Паника обработчика учитывается как 500 и пробрасывается дальше;
// http.ErrAbortHandler — штатный обрыв ответа, он не считается. Информационный
// ответ 1xx (кроме 101) кодом запроса не становится.
//
// Реестр передаётся явно (New), глобальной регистрации нет. Метрики рантайма
// Go пакет не собирает: их отдаёт collectors.NewGoCollector реестра
// приложения.
